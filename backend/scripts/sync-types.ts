// Usage: yarn sync-types | yarn sync-types --check
// The backend owns the types and rules shared with the browser (src/shared). The frontend gets a generated copy so
// the two packages never drift. --check fails when the copy differs; without it the copy is rewritten.
import { mkdirSync, readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";

const SOURCE = path.resolve(__dirname, "../src/shared");
const FRONTEND = path.resolve(__dirname, "../../frontend");
const TARGET = path.join(FRONTEND, "src/types/generated");
const HEADER = "// Generated by backend/scripts/sync-types.ts from backend/src/shared. Do not edit here.\n";

function expected(): Map<string, string> {
  const files = new Map<string, string>();
  for (const name of readdirSync(SOURCE).filter((f) => f.endsWith(".ts"))) {
    files.set(name, HEADER + readFileSync(path.join(SOURCE, name), "utf8"));
  }
  return files;
}

function main(): void {
  const check = process.argv.includes("--check");
  if (!existsSync(FRONTEND)) {
    console.log("No frontend package yet (phase 5). Nothing to sync.");
    return;
  }
  const stale: string[] = [];
  for (const [name, content] of expected()) {
    const file = path.join(TARGET, name);
    const current = existsSync(file) ? readFileSync(file, "utf8") : null;
    if (current === content) continue;
    stale.push(name);
    if (!check) {
      mkdirSync(TARGET, { recursive: true });
      writeFileSync(file, content);
    }
  }
  if (check && stale.length > 0) {
    console.error(
      `Out of date: ${stale.join(", ")}. Run \`yarn sync-types\` in backend and commit the result.`,
    );
    process.exitCode = 1;
    return;
  }
  console.log(stale.length > 0 ? `Updated: ${stale.join(", ")}` : "Shared types are in sync.");
}

main();
